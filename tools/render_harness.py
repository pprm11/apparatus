#!/usr/bin/env python3
"""Render the user's context (source of truth: ~/.claude) for harnesses other than Claude Code.

Codex: writes ~/.codex/AGENTS.md (CLAUDE.md with every @import inlined, the Codex adapter in place of the
Claude one, then rules/*.md) and links each portable skill from ~/.claude/skills into ~/.codex/skills.
Skills listed as claude_only in ~/.claude/harness/skills.json are not linked. Folders in ~/.codex/skills
that are not links into ~/.claude/skills (Codex's own skills) are never touched.

Usage: python -I tools/render_harness.py [--dry-run] [--claude-home ~/.claude] [--codex-home ~/.codex]
       python -I tools/render_harness.py --company NAME [--manifest M] [--companies F] [--codex-home DIR]
Run by sync.sh every hour; safe to run by hand.

--company NAME renders the AGENTS.md of one company only, from the layer repos (see tools/compose.py): superego and
id plus the ego and collective of NAME. It reads nothing from ~/.claude. It writes <codex-home>/AGENTS.md and copies
the company's portable skills (not claude_only) into <codex-home>/skills, touching only folders it recorded in
.company-skills.json there, so Codex's own skills survive. --codex-home defaults to the company's `home.codex` in companies.json, and a
missing folder is not created.
"""
import argparse
import glob
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # python -I drops the script dir

MAX_BYTES = 32 * 1024  # Codex stops reading instruction files past this size
WARN_BYTES = MAX_BYTES * 7 // 8  # 28,672: early warning, so the limit never arrives as a surprise
WARN_TITLE = "AGENTS.md do Codex perto do limite de 32 KiB"
IMPORT = re.compile(r"^@(~?[^\s]+\.md)\s*$")


def read_text(path: str) -> str | None:
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def expand(path: str, home: str, base: str | None = None) -> str:
    """@~/.claude/x.md -> <claude_home>/x.md, so a test home works too. `./x.md` and `../x.md` are relative
    to the folder of the importing file (`base`), as in Claude Code."""
    if base and path.startswith(("./", "../")):
        return os.path.normpath(os.path.join(base, path))
    path = os.path.expanduser(path) if not path.startswith("~/.claude/") else os.path.join(home, path[len("~/.claude/"):])
    return os.path.normpath(path)


def inline(path: str, home: str, harness: str, seen: set[str], sizes: list | None = None) -> str:
    out, own = [], []
    if sizes is not None:
        sizes.append((path, 0))
        slot = len(sizes) - 1
    with open(path, encoding="utf-8") as fh:
        for line in fh.read().splitlines():
            m = IMPORT.match(line.strip())
            if not m:
                out.append(line)
                own.append(line)
                continue
            target = expand(m.group(1), home, os.path.dirname(path))
            if os.path.basename(os.path.dirname(target)) == "harness":
                target = os.path.join(os.path.dirname(target), f"{harness}.md")
            if target in seen or not os.path.isfile(target):
                continue
            seen.add(target)
            out.append(inline(target, home, harness, seen, sizes))
    if sizes is not None:
        sizes[slot] = (path, len("\n".join(own).encode("utf-8")))
    return "\n".join(out)


def render_agents_md(claude_home: str, harness: str = "codex", sizes: list | None = None) -> str:
    """`sizes`, when given, is filled with (source path, own bytes) for the breakdown in the size warning."""
    parts = [
        f"<!-- Generated by tools/render_harness.py of superego from {claude_home}. "
        "Do not edit: change the source and the hourly sync regenerates this file. -->",
        inline(os.path.join(claude_home, "CLAUDE.md"), claude_home, harness, set(), sizes),
    ]
    for rule in sorted(glob.glob(os.path.join(claude_home, "rules", "*.md"))):
        with open(rule, encoding="utf-8") as fh:
            parts.append(fh.read().strip())
        if sizes is not None:
            sizes.append((rule, len(parts[-1].encode("utf-8"))))
    return "\n\n".join(p.strip() for p in parts) + "\n"


def link_target(path: str) -> str | None:
    try:
        return os.path.normcase(os.path.abspath(os.readlink(path)).removeprefix("\\\\?\\"))
    except (OSError, ValueError):
        return None


def make_link(src: str, dst: str) -> None:
    if os.name == "nt":  # a junction needs no admin rights, unlike a symlink
        res = subprocess.run(["cmd", "/c", "mklink", "/J", dst, src], capture_output=True, text=True)
        if res.returncode:
            raise OSError(f"mklink /J {dst}: {(res.stdout + res.stderr).strip()}")
    else:
        os.symlink(src, dst, target_is_directory=True)


def sync_skills(claude_home: str, codex_home: str, dry_run: bool) -> list[str]:
    src_root = os.path.join(claude_home, "skills")
    dst_root = os.path.join(codex_home, "skills")
    manifest = os.path.join(claude_home, "harness", "skills.json")
    claude_only = set(json.loads(read_text(manifest) or "{}").get("claude_only", []))
    wanted = {
        name for name in (os.listdir(src_root) if os.path.isdir(src_root) else [])
        if name != "synced" and name not in claude_only and os.path.isfile(os.path.join(src_root, name, "SKILL.md"))
    }
    log = []
    os.makedirs(dst_root, exist_ok=True)
    ours = os.path.normcase(os.path.abspath(src_root))
    for name in sorted(os.listdir(dst_root)):  # drop our stale links only
        target = link_target(os.path.join(dst_root, name))
        if target and target.startswith(ours) and name not in wanted:
            log.append(f"unlink {name}")
            if not dry_run:
                os.rmdir(os.path.join(dst_root, name)) if os.name == "nt" else os.unlink(os.path.join(dst_root, name))
    for name in sorted(wanted):
        dst = os.path.join(dst_root, name)
        if os.path.lexists(dst):
            if link_target(dst) is None:
                log.append(f"skip {name}: a real folder already exists in {dst_root}")
            continue
        log.append(f"link {name}")
        if not dry_run:
            make_link(os.path.join(src_root, name), dst)
    return log


def size_warning(size: int, limit: int, sizes: list, claude_home: str) -> str:
    rows = sorted(sizes, key=lambda r: -r[1])
    breakdown = ", ".join(f"{os.path.relpath(p, claude_home).replace(os.sep, '/')}={n}" for p, n in rows)
    return f"AGENTS.md is {size} bytes, {size * 100 // limit}% of the {limit} byte limit. Sources: {breakdown}"


def raise_size_item(message: str, claude_home: str) -> bool:
    """One open inbox item per size problem (the hourly sync would otherwise add one every hour)."""
    import decisions  # noqa: E402  (here: decisions pulls in the session readers)

    with decisions.locked(claude_home):
        data = decisions.load(claude_home)
        if any(i["title"] == WARN_TITLE and i["status"] == "open" for i in data["items"]):
            return False
        decisions.new_item(data, "manual", WARN_TITLE, level="superego", detail=message,
                           options=["A enxugar as fontes", "B subir o limite do aviso"], source="tools/render_harness.py")
        decisions.save(data, claude_home)
    return True


def render_company(args: argparse.Namespace) -> int:
    """--company mode: compose into a temp folder, then write only the company's AGENTS.md."""
    import tempfile

    import companies  # noqa: E402
    import compose  # noqa: E402
    import layers  # noqa: E402
    import roots  # noqa: E402

    data = companies.load(args.companies)
    codex_home = args.codex_home or companies.home_of(args.company, "codex", data)
    if not codex_home:
        print(f"no home.codex for company {args.company!r} in companies.json; pass --codex-home")
        return 1
    codex_home = os.path.normpath(os.path.expanduser(str(codex_home)))
    if not os.path.isdir(codex_home):
        print("no Codex home, nothing to render")
        return 0
    man = layers.load_manifest(layers.expand(args.manifest or roots.default_manifest(args.root)))
    with tempfile.TemporaryDirectory() as tmp:
        rc = compose.compose_company(man, args.company, data, tmp, args.codes or roots.layers_root(args.root), note=lambda m: print(m, file=sys.stderr))
        if rc:
            return rc
        text = read_text(os.path.join(tmp, "AGENTS.md")) or ""
    size = len(text.encode("utf-8"))
    if size > args.max_bytes:
        print(f"AGENTS.md would be {size} bytes, over the {args.max_bytes} Codex limit; not written")
        return 1
    if size > args.max_bytes * 7 // 8:
        print(f"warning: AGENTS.md is {size} bytes, {size * 100 // args.max_bytes}% of the {args.max_bytes} byte limit")
    dst = os.path.join(codex_home, "AGENTS.md")
    if read_text(dst) != text:
        print(f"write {dst} ({size} bytes)")
        if not args.dry_run:
            with open(dst, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
    plan = compose.company_plan(man, args.company, data, args.codes, note=lambda m: None)
    only_claude = compose.claude_only_skills(plan["superego"])
    portable = {n: src for n, src in plan["skills"].items() if n not in only_claude}
    skills_dir = os.path.join(codex_home, "skills")
    if portable or os.path.isfile(os.path.join(skills_dir, compose.SKILL_MARKER)):
        for name in compose.sync_company_skills(portable, skills_dir, own_all=False, dry_run=args.dry_run):
            print(f"skill {name}")
    return 0


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--claude-home", default=os.path.expanduser("~/.claude"))
    ap.add_argument("--codex-home", default=None, help="default ~/.codex, or the company's home.codex with --company")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--max-bytes", type=int, default=MAX_BYTES, help="hard limit; the warning starts at 7/8 of it")
    ap.add_argument("--manifest", default=os.environ.get("SYNC_MANIFEST"),
                    help="psique manifest with the per-layer byte budgets; without it (tests, ad-hoc runs) only the hard limit applies")
    ap.add_argument("--company", help="render only this company's AGENTS.md (see the module docstring)")
    ap.add_argument("--companies", help="with --company: companies.json (default ~/.claude/companies.json)")
    ap.add_argument("--root", help="folder holding the layer repos (default: $PSIQUE_ROOT, else the parent of this checkout)")
    ap.add_argument("--codes", help="with --company: folder holding the layer repos (default: the root)")
    args = ap.parse_args()
    if args.company:
        args.codex_home = os.path.expanduser(args.codex_home) if args.codex_home else None
        return render_company(args)
    args.codex_home = args.codex_home or os.path.expanduser("~/.codex")
    args.claude_home, args.codex_home = os.path.normpath(args.claude_home), os.path.normpath(args.codex_home)
    if not os.path.isdir(args.codex_home):
        print("no Codex home, nothing to render")
        return 0

    sizes: list = []
    text = render_agents_md(args.claude_home, sizes=sizes)
    size = len(text.encode("utf-8"))
    limit = args.max_bytes
    if size > limit * 7 // 8:
        warning = size_warning(size, limit, sizes, args.claude_home)
        print("warning: " + warning)
        if not args.dry_run:
            raise_size_item(warning, args.claude_home)
    dst = os.path.join(args.codex_home, "AGENTS.md")
    old = read_text(dst)
    if size > limit:
        print(f"AGENTS.md would be {size} bytes, over the {limit} Codex limit; not written")
        return 1
    # Per-layer byte budgets (psique manifest): a layer over its budget blocks the render, like the hard limit.
    manifest = os.path.normpath(os.path.expanduser(args.manifest)) if args.manifest else ""
    if manifest and os.path.isfile(manifest):
        import context_budget  # noqa: E402

        rep = context_budget.report(manifest, args.claude_home)
        for w in rep["warnings"]:
            print("budget warning: " + w)
        if rep["problems"]:
            for p in rep["problems"]:
                print("budget problem: " + p)
            print("AGENTS.md not written: a layer is over its byte budget (tools/context_budget.py)")
            return 1
    if old != text:
        print(f"write {dst} ({size} bytes)")
        if not args.dry_run:
            with open(dst, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
    for line in sync_skills(args.claude_home, args.codex_home, args.dry_run):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
