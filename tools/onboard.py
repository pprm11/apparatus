def collect_answers(ctx: Ctx, args: argparse.Namespace) -> dict:
    gh_user = ""
    if args.git_host == "github" and ctx.which("gh"):
        gh_user = ctx.sh.run(["gh", "api", "user", "--jq", ".login"], check=False).stdout.strip()
    name = args.name or ctx.ask("Your name", ctx.sh.run(["git", "config", "user.name"], check=False).stdout.strip())
    github = args.github or ctx.ask("Your GitHub username", gh_user)
    if not name or not github:
        raise OnboardError("--name and --github are missing (or run in an interactive terminal)")
    if not re.fullmatch(r"[A-Za-z0-9-]+", github):
        raise OnboardError(f"invalid GitHub username: {github!r}")
    codes = layers_folder(ctx, args.codes)
    roots: dict[str, list[str]] = {}
    for item in args.root:
        company, _, path = item.partition("=")
        roots.setdefault(company, []).append(path.replace(chr(92), "/"))
    return {"name": name, "github": github, "codes": codes.resolve() if codes.exists() else codes, "roots": roots,
            "self_repo": args.self_repo, "id_repo": args.id_repo, "superego_ref": args.superego_ref}


def validate_specs(specs: Sequence[LayerSpec], a: dict, allow_empty: bool = False,
                   context_home: Path | None = None) -> None:
    cfg = privacy.load_config(context_home=context_home)
    if not specs and not allow_empty:
        raise OnboardError("no shared layer: pass --layer ego:NAME=URL and --layer collective:NAME=URL")
    for s in specs:
        bad = privacy.forbidden_layer(s.url, cfg)
        if bad:
            raise OnboardError(f"{s.url} is a personal layer or another company's layer and cannot be attached here")
        if s.repo == a["id_repo"] and slug_of(s.url)[0].lower() != a["github"].lower():
            raise OnboardError(f"{s.url} looks like another person's id; the id is always your own")
        if s.level == "ego" and slug_of(s.url)[0].lower() != a["github"].lower():
            raise OnboardError(f"{s.url} is another person's ego; the ego is always your own (only the collective is shared)")


def accessible_collectives(ctx: Ctx) -> list[str]:
    """`owner/collective-*` repos the logged-in person can read (their own, shared with them, or of an org)."""
    res = ctx.sh.run(["gh", "api", "user/repos?affiliation=owner,collaborator,organization_member&per_page=100",
                      "--paginate", "--jq", '.[] | select(.name | startswith("collective-")) | .full_name'], check=False)
    return sorted(set((res.stdout or "").split()))


def copy_template(src: Path, dst: Path, vals: dict[str, str], team: str) -> None:
    for f in sorted(p for p in src.rglob("*") if p.is_file() and "__pycache__" not in p.parts):
        text = fill(f.read_text(encoding="utf-8"), vals).replace("<team>", team).replace("YYYY-MM-DD", datetime.date.today().isoformat())
        write(dst / f.relative_to(src), text)


def create_collective(ctx: Ctx, host: GitHubHost, a: dict, team: str, deny: Sequence[str]) -> LayerSpec:
    """A new collective in the person's own private repo: templates/collective plus the CI kit (gates, deny-list)."""
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", team):
        raise OnboardError(f"invalid collective name: {team!r} (use lowercase letters, digits and hyphens)")
    repo, dest = f"collective-{team}", a["codes"] / f"collective-{team}"
    today = datetime.date.today()
    vals = {"team": team, "github": a["github"], "iso": today.isoformat(),
            "review": (today + datetime.timedelta(days=182)).isoformat()}

    def populate(d: Path) -> None:
        copy_template(SUPEREGO / "templates" / "collective", d, vals, team)
        copy_template(SUPEREGO / "kits" / "collective", d, vals, team)

    step(ctx, "ok", f"new collective {team}", ensure_own_repo(ctx, host, a, repo, dest, populate))
    if type(host) is GitHubHost:
        names = ",".join(deny)
        if names:
            ctx.sh.run(["gh", "variable", "set", "COLLECTIVE_DENY_COMPANIES", "--repo", f"{a['github']}/{repo}",
                        "--body", names], check=False)
            step(ctx, "ok", "other-companies term list", f"{len(deny)} term(s) in the collective CI")
        else:
            step(ctx, "warn", "other-companies term list",
                 f"empty: the CI of {repo} fails until you set COLLECTIVE_DENY_COMPANIES (gh variable set)")
    return LayerSpec("collective", team, host.url(a["github"], repo))


def with_own_egos(specs: Sequence[LayerSpec], a: dict, host: GitHubHost) -> list[LayerSpec]:
    """Every collective gets the person's OWN ego `ego-NAME` in their account (created from templates/ego)."""
    out = list(specs)
    have = {s.name for s in out if s.level == "ego"}
    for s in specs:
        if s.level == "collective" and s.name not in have:
            out.append(LayerSpec("ego", s.name, host.url(a["github"], f"ego-{s.name}")))
            have.add(s.name)
    return out


def choose_layers(ctx: Ctx, args: argparse.Namespace, a: dict, host: GitHubHost) -> list[LayerSpec]:
    """The collective step: attach by URL (--layer), create a new one (--new-collective), pick from the ones the
    person can access (interactive) or skip it (--no-collective). Each layer carries its own company name."""
    specs = [parse_layer(x) for x in args.layer]
    for team in args.new_collective:
        specs.append(create_collective(ctx, host, a, team, args.deny_company))
    if args.no_collective or any(s.level == "collective" for s in specs):
        return with_own_egos(specs, a, host)
    if not ctx.interactive:
        raise OnboardError("collective step: pass --layer collective:NAME=URL, --new-collective NAME or --no-collective")
    found = accessible_collectives(ctx) if args.git_host == "github" and ctx.which("gh") else []
    ctx.say("Collective layers (what your team shares) you can access:")
    for i, full in enumerate(found, 1):
        ctx.say(f"  {i}) {full}")
    ctx.say("  N) create a new private collective in your account")
    ans = ctx.ask("Which to attach? Numbers separated by commas, N to create, empty for none", "")
    for tok in (t.strip() for t in ans.split(",") if t.strip()):
        if tok.lower() == "n":
            team = ctx.ask("Name of the new collective (lowercase)", "")
            deny = ctx.ask("Terms of OTHER companies that must not enter it (comma-separated)", "")
            specs.append(create_collective(ctx, host, a, team, [d.strip() for d in deny.split(",") if d.strip()]))
        elif tok.isdigit() and 0 < int(tok) <= len(found):
            owner, repo = found[int(tok) - 1].split("/")
            team = repo.removeprefix("collective-")
            specs.append(LayerSpec("collective", team, host.url(owner, repo)))
        else:
            raise OnboardError(f"invalid option: {tok}")
    for company in sorted({s.name for s in specs}):
        if company not in a["roots"]:
            folder = ctx.ask(f"Folder of {company} projects (the collective only loads there)", f"{layers_folder(ctx, None)}/{company}")
            a["roots"][company] = [folder]
    return with_own_egos(specs, a, host)


def ensure_tools(ctx: Ctx, keys: Sequence[str]) -> list[str]:
    """Install missing tools with the OS package manager (bootstrap.PACKAGES); returns the ones still missing."""
    import bootstrap  # noqa: PLC0415  (heavy import only for the vault step)
    mgr = bootstrap.manager(bootstrap.Ctx(plat=ctx.plat, runner=bootstrap.Runner(), which=ctx.which, home=ctx.home))
    for pkg in (p for p in bootstrap.PACKAGES if p.key in keys and not ctx.which(p.command)):
        cmd = bootstrap.install_command(pkg, mgr) if mgr else None
        if cmd:
            ctx.say(f"Instalando {pkg.key}: {' '.join(cmd)}")
            ctx.sh.run(cmd, check=False, interactive=True)
        else:
            ctx.say(f"Install {pkg.key} by hand: {pkg.manual or 'with your package manager'}")
    return [k for k in keys if not ctx.which(next(p.command for p in bootstrap.PACKAGES if p.key == k))]


def vault_step(ctx: Ctx, mode: str, region: str, state: dict) -> bool:
    """Own Bitwarden vault + own age identity. True when the identity is safe in the vault and the recipient saved."""
    if mode == "ask":
        mode = "yes" if ctx.interactive and ctx.ask("Set up your Bitwarden vault (age key) now? (y/n)", "n").lower().startswith("y") else "skip"
    if mode == "skip":
        step(ctx, "skipped", "vault", "run `onboard.py vault` whenever you like")
        return False
    missing = ensure_tools(ctx, ("bw", "age"))
    if missing:
        step(ctx, "missing", "vault", f"tool(s) not installed: {', '.join(missing)}; open a new terminal and run `onboard.py vault`")
        return False
    if ctx.interactive:
        ctx.say(onboard_vault.HUMAN_STEPS.format(tld="eu" if region == "eu" else "com"))
    vault = onboard_vault.Vault(ctx.sh, ctx.say)
    vault.set_region(region)
    if not vault.unlock(ctx.interactive):
        step(ctx, "skipped", "vault", "locked: set BW_SESSION (bw unlock --raw) or run `onboard.py vault` in a terminal")
        return False
    status, recipient = vault.ensure_identity()
    target = ctx.home / ".config" / "id-context"  # legacy folder name, kept so existing recipients keep working
    for anc in [target, *target.parents]:  # remember the folders we create, for uninstall
        if anc.exists():
            break
        state["created_dirs"].append(str(anc))
    path = onboard_vault.save_recipient(ctx.home, recipient)
    state.setdefault("extra_files", []).append(str(path))
    step(ctx, "ok", "vault", f"age key {status}; only the PUBLIC key was left in {path}")
    return True


def run_initial_sync(ctx: Ctx, manifest: Path) -> None:
    """One update right after the jobs are registered, with its result shown."""
