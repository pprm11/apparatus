def last_result(ctx: Ctx, short: str) -> str:
    f = ospaths.state_dir(ctx.plat, ctx.sh.env, ctx.home) / "logs" / f"{short}.last.json"
    try:
        d = read_json(f)
        return f"exit {d['exit']} at {d['ts']}"
    except (OSError, ValueError, KeyError):
        return "has not run yet"


def job_rows(ctx: Ctx, manifest: Path) -> list[dict]:
    raw = read_json(manifest)
    enabled = set(raw["jobs"]) if raw.get("runner") == "python" and "jobs" in raw else None
    table = scheduler.jobs_for(manifest, ctx.plat, all_jobs=True)
    be = scheduler.backend_for()
    reg = be.status(table)
    now = datetime.datetime.now()
    return [{"job": j, "enabled": enabled is None or j.short in enabled, "registered": reg.get(j.name, False),
             "last": last_result(ctx, j.short), "next": scheduler.next_run(j.trigger, now).strftime("%Y-%m-%d %H:%M")}
            for j in table]


def job_checks(ctx: Ctx, manifest: Path) -> list[doctor.Check]:
    out = []
    for r in job_rows(ctx, manifest):
        if not r["enabled"]:
            out.append(doctor.Check(f"job-{r['job'].short}", doctor.OK, "turned off on purpose"))
            continue
        ok = r["registered"]
        out.append(doctor.Check(f"job-{r['job'].short}", doctor.OK if ok else doctor.WARN,
                                f"{'registered' if ok else 'NOT registered'}; last: {r['last']}; next: {r['next']}",
                                "" if ok else "onboard.py jobs install"))
    return out


def cmd_jobs(ctx: Ctx, args: argparse.Namespace) -> int:
    state = load_state(ctx)
    manifest = Path(args.manifest or state.get("manifest", ""))
    if not manifest.is_file():
        raise OnboardError("manifest not found: run `onboard.py init` first")
    raw = read_json(manifest)
    table = {j.short: j for j in scheduler.jobs_for(manifest, ctx.plat, all_jobs=True)}
    be = scheduler.backend_for()
    if args.action == "status":
        for r in job_rows(ctx, manifest):
            ctx.say(f"{r['job'].short:<8} {'enabled' if r['enabled'] else 'disabled':<9} "
                    f"{'registered' if r['registered'] else 'not registered':<15} last: {r['last']}; next: {r['next']}")
        return 0
    if args.action in ("enable", "disable"):
        if args.name not in table:
            raise OnboardError(f"unknown job: {args.name} (available: {', '.join(table)})")
        if raw.get("runner") != "python":
            raise OnboardError("this manifest uses the full job set; use scheduler.py")
        jobs = [j for j in raw.get("jobs", ["update"]) if j != args.name]
        if args.action == "enable":
            jobs.append(args.name)
        raw["jobs"] = sorted(set(jobs), key=list(table).index)
        write_json(manifest, raw)
        if commit_all(ctx.sh, manifest.parent, f"chore: {args.action} job {args.name}"):
            ctx.sh.run(["git", "push", "--quiet", "origin", "HEAD"], cwd=manifest.parent, check=False)
        job = table[args.name]
        done = be.install([job]) if args.action == "enable" else be.remove([job])
        step(ctx, "ok", f"job {args.name}", f"{'enabled' if args.action == 'enable' else 'disabled'}: {', '.join(done)}")
        return 0
    if args.action in ("install", "remove"):
        jobs = scheduler.jobs_for(manifest, ctx.plat)
        done = be.install(jobs) if args.action == "install" else be.remove(list(table.values()))
        state["jobs"] = done if args.action == "install" else []
        save_state(ctx, state)
        step(ctx, "ok", f"jobs {args.action}", ", ".join(done))
        return 0
    if args.name not in table:
        raise OnboardError(f"unknown job: {args.name}")
    res = ctx.sh.run([sys.executable, "-I", str(SUPEREGO / "tools" / "run_job.py"), "--manifest", str(manifest), args.name],
                     check=False)
    step(ctx, "ok" if res.returncode == 0 else "failed", f"job {args.name}", f"code {res.returncode}; {last_result(ctx, args.name)}")
    return res.returncode


