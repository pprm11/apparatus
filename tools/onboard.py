def build_manifest(a: dict, ctx: Ctx, specs: Sequence[LayerSpec], host: GitHubHost) -> dict:
    base = read_json(TEMPLATES / "self" / "manifest.json")
    base["id"] = re.sub(r"[^a-z0-9]+", "-", a["github"].lower()).strip("-")
    codes = a["codes"]
    sup_url = ctx.sh.run(["git", "remote", "get-url", "origin"], cwd=SUPEREGO, check=False).stdout.strip()
    if is_github(sup_url):  # HTTPS through gh works for a person who never set up SSH keys
        sup_url = f"https://github.com/{'/'.join(slug_of(sup_url))}.git"
        if type(host) is GitHubHost:
            host.use_gh_credentials(SUPEREGO, sup_url)
    sup = {"level": "superego", "path": under_home(SUPEREGO / "superego", ctx.home), "repo": sup_url, "mode": "readonly",
           "ref": a["superego_ref"], "active": True}
    shared = []
    for s in specs:
        entry = {"level": s.level, "name": s.name, "company": s.name, "path": under_home(codes / s.repo, ctx.home),
                 "repo": s.url, "active": True}
        if s.level == "collective":  # the only shared content layer: pulled, never written from here
            entry.update(mode="readonly", ref="")
        shared.append(entry)
    shared.sort(key=lambda l: layers.LEVELS.index(l["level"]))
    mine = {"level": "id", "name": a["github"], "path": under_home(codes / a["id_repo"], ctx.home),
            "repo": host.url(a["github"], a["id_repo"]), "active": True}
    if len({x["company"] for x in shared}) > 1:  # companies never mix: each one gets its own home instead
        for x in shared:
            x["active"] = False
    base["jobs"] = a.get("jobs", ["update"])
    base["layers"] = [sup, *shared, mine]
    return base


def build_companies(roots: dict[str, list[str]], specs: Sequence[LayerSpec]) -> dict:
    companies = {}
    for s in specs:
        c = companies.setdefault(s.name, {"prefixes": roots.get(s.name, [])})
        c[s.level] = s.repo
    return {"companies": companies, "default": None}


def materialize_self(dest: Path, a: dict, manifest: dict) -> None:
    vals = {"name": a["name"], "github": a["github"], "date": time.strftime("%Y-%m-%d")}
    for f in ("README.md", ".gitignore"):
        src = TEMPLATES / "self" / f
        write(dest / f, fill(src.read_text(encoding="utf-8"), vals))
    write_json(dest / "manifest.json", manifest)


def materialize_id(dest: Path, a: dict) -> None:
    src = TEMPLATES / "id"
    vals = {"name": a["name"], "github": a["github"], "date": time.strftime("%Y-%m-%d")}
    for rel in ("layer.json", "README.md", "global/preferences.md", "global/personal-glossary.md", "pdi/README.md"):
        text = fill((src / rel).read_text(encoding="utf-8"), vals)
        if rel.endswith("preferences.md"):
            text = text.replace("# Personal preferences of the user (example, replace with your own)",
                                f"# Preferences of {a['name']} (example, replace with your own)")
        if rel.endswith("personal-glossary.md"):
            text = text.replace("YYYY-MM-DD", vals["date"])
        write(dest / rel, text)
    write(dest / ".gitignore", "*.age.key\n.DS_Store\n")


def materialize_ego(dest: Path, a: dict, team: str) -> None:
    """The person's own ego for one collective: private notes, preferences and work context for that company."""
    src = TEMPLATES / "ego"
    date = datetime.date.today().isoformat()
    names = {"global/glossary-company.md": f"global/glossary-{team}.md", "global/rules-company.md": f"global/rules-{team}.md",
             "layer.json": "layer.json", "README.md": "README.md"}
    for rel, out in names.items():
        text = (src / rel).read_text(encoding="utf-8").replace("<company>", team).replace("YYYY-MM-DD", date)
        write(dest / out, text)
    write(dest / ".gitignore", ".DS_Store\n")


def ensure_own_repo(ctx: Ctx, host: GitHubHost, a: dict, repo: str, dest: Path, populate: Callable[[Path], None]) -> str:
    """Create the local repo from a template, commit, publish it private under the person's account. Idempotent."""
    owner = a["github"]
    created = []
    if not (dest / ".git").exists():
        if host.exists(owner, repo):
            host.clone(host.url(owner, repo), dest)
            created.append("cloned")
        else:
            dest.mkdir(parents=True, exist_ok=True)
            ctx.sh.run(["git", "init", "--quiet", "-b", "main"], cwd=dest)
            created.append("created")
    git_identity(ctx.sh, dest, a["name"], owner)
    populate(dest)
    committed = commit_all(ctx.sh, dest, "feat: initial layer from the superego template" if "created" in created
                           else "chore: refresh from the superego template")
    if not ctx.sh.out(["git", "remote"], cwd=dest):
        host.publish(owner, repo, dest)
        created.append("published (private)")
    elif committed:
        ctx.sh.run(["git", "push", "--quiet", "origin", "HEAD"], cwd=dest, check=False)
    return ", ".join(created) or "already existed"


# --------------------------------------------------------------------------- restore and compose

def excluded_skills(layer: dict) -> set[str]:
    return set(layer["config"].get("install_exclude", {}).get("skills", []))


def layer_payload(layer: dict) -> list[Path]:
    """Folders and files of a layer repo that reach the person's machine (what restore copies)."""
    root, cfg = Path(layer["path"]), layer["config"]
    paths = [root / d for d in ("global", "rules", "memory", "harness", "scripts") if (root / d).exists()]
    skip = excluded_skills(layer)
    skills = root / "skills"
    if skills.is_dir():
        paths += [p for p in sorted(skills.iterdir()) if p.name not in skip]
    paths += [root / d for d in cfg.get("dirs", []) if (root / d).exists()]
    paths += [root / f for f in cfg.get("files", []) if (root / f).exists()]
    paths.append(root / "layer.json")
    return [p for p in paths if p.exists()]


def copy_into(src: Path, dst: Path, home: Path, written: list[str], skip_names: Sequence[str] = ()) -> None:
    files = [src] if src.is_file() else [p for p in sorted(src.rglob("*")) if p.is_file()]
    for f in files:
        rel = Path() if src.is_file() else f.relative_to(src)
        if any(part in (".git", *skip_names) for part in rel.parts):
            continue
        target = dst if src.is_file() else dst / rel
        data = f.read_bytes()
        if not (target.is_file() and target.read_bytes() == data):
            target.parent.mkdir(parents=True, exist_ok=True)
            tmp = target.with_name(target.name + ".tmp")
            tmp.write_bytes(data)
            os.replace(tmp, target)
        written.append(target.relative_to(home).as_posix())


def restore_layer(layer: dict, claude: Path) -> list[str]:
    """Python port of restore.sh for one layer: global/, rules/, skills/, memory/, layer.json dirs and files.

    Returns the files written, relative to the Claude home. settings.json is never touched.
    """
    # Persona skills are owned by compose and may carry local overlays and receipts.
    if layer["level"] == "persona":
        return []
    root, cfg, written = Path(layer["path"]), layer["config"], []
    for f in sorted((root / "global").glob("*")) if (root / "global").is_dir() else []:
        if f.name != "settings.json":
            copy_into(f, claude / f.name, claude, written)
    if (root / "rules").is_dir():
        copy_into(root / "rules", claude / "rules", claude, written)
    skip = excluded_skills(layer)
    if (root / "skills").is_dir():
        for sk in sorted((root / "skills").iterdir()):
            if sk.is_dir() and sk.name not in skip:
                copy_into(sk, claude / "skills" / sk.name, claude, written)
    for proj in sorted((root / "memory").glob("*/")) if (root / "memory").is_dir() else []:
        copy_into(proj, claude / "projects" / proj.name / "memory", claude, written)
    for d in cfg.get("dirs", []):
        if (root / d).is_dir():
            copy_into(root / d, claude / d, claude, written)
    for f in cfg.get("files", []):
        if (root / f).is_file():
            copy_into(root / f, claude / f, claude, written)
    return written


def backup_foreign(path: Path, marker: str, state: dict, key: str) -> None:
    """Keep the person's own CLAUDE.md or AGENTS.md (not generated by us) as <name>.pre-self before overwriting."""
    markers = (marker,) if isinstance(marker, str) else marker
    head = path.read_text(encoding="utf-8", errors="replace")[:400] if path.is_file() else ""
    if path.is_file() and not any(m in head for m in markers):
        bak = path.with_name(path.name + ".pre-self")
        legacy = path.with_name(path.name + ".pre-psique")
        if not bak.exists() and legacy.exists():
            bak = legacy
        if not bak.exists():
            shutil.copy2(path, bak)
        state["backups"][key] = str(bak)


def migrate_names(ctx: Ctx, manifest: Path) -> None:
    """Pre-1.0 rename: rename or drop files and skills an older install still has (tools/renames.json).

    An install's files come from the layer repos, so stale duplicates and retired files are removed here."""
    for line in migrate.apply(manifest, ctx.claude, migrate.load_map(), repos=False, prune=True):
        step(ctx, "migr", "rename", line)


def compose(ctx: Ctx, manifest: Path, state: dict) -> None:
    migrate_names(ctx, manifest)
    backup_foreign(ctx.claude / "CLAUDE.md", GENERATED_CLAUDE, state, "CLAUDE.md")
    backup_foreign(ctx.codex / "AGENTS.md", GENERATED_CODEX, state, "AGENTS.md")
    ctx.codex.mkdir(parents=True, exist_ok=True)
    ctx.sh.run([sys.executable, "-I", str(SUPEREGO / "tools" / "compose.py"), "--manifest", str(manifest),
                "--claude-home", str(ctx.claude), "--codex-home", str(ctx.codex)])


def person_words(a: dict) -> list[str]:
    return privacy.name_words(a["name"], a["github"])


def source_hits(man: dict, a: dict, context_home: Path | None = None) -> list[privacy.Hit]:
    """Scan what the shared layers (superego, collective) would put on this machine. id and ego are the person's own."""
    pats = privacy.patterns(privacy.load_config(context_home=context_home), allow_words=person_words(a))
    hits: list[privacy.Hit] = []
    for layer in man["layers"]:
        if layer["level"] not in ("id", "ego") and (layer.get("active", True) or layer.get("company")):
            hits += privacy.scan_paths(layer_payload(layer), pats, Path(layer["path"]))
    return hits


def output_hits(ctx: Ctx, written: Sequence[str], a: dict) -> list[privacy.Hit]:
    pats = privacy.patterns(privacy.load_config(context_home=ctx.claude), allow_words=person_words(a))
    files = [ctx.claude / "CLAUDE.md", ctx.codex / "AGENTS.md", *(ctx.claude / w for w in written)]
    hits = privacy.scan_paths([f for f in files if f.exists()], pats, ctx.claude)
    # Line 1 of AGENTS.md is the render stamp with the person's own home path, not layer content.
    return [h for h in hits if not (h.path.endswith("AGENTS.md") and h.line == 1)]


