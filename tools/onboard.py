def latest_tag(sh: Sh, repo: Path) -> str:
    tags = [t for t in sh.out(["git", "tag", "--list", "v*", "--sort=-v:refname"], cwd=repo).splitlines() if t]
    return tags[0] if tags else ""


def pull_layer(ctx: Ctx, layer: dict, upgrade: bool) -> tuple[str, str]:
    """(status, detail) for one readonly layer. A pinned ref moves only with --upgrade; others fast-forward."""
    repo, sh = Path(layers.repo_root(layer["path"])), ctx.sh
    if not (repo / ".git").exists():
        return "failed", f"{repo} does not exist"
    if not sh.out(["git", "remote"], cwd=repo):
        return "skipped", "no remote"
    if sh.out(["git", "status", "--porcelain"], cwd=repo):
        return "skipped", "local changes in the (read-only) layer: discard them"
    sh.run(["git", "fetch", "--tags", "--quiet"], cwd=repo, check=False)
    ref = layer.get("ref") or ""
    if ref:
        newest = latest_tag(sh, repo)
        if upgrade and newest and newest != ref:
            sh.run(["git", "checkout", "--quiet", newest], cwd=repo)
            layer["ref"] = newest
            return "ok", f"{ref} -> {newest}"
        sh.run(["git", "checkout", "--quiet", ref], cwd=repo)
        return "ok", f"pinned at {ref}" + (f" ({newest} exists: use update --upgrade)" if newest and newest != ref else "")
    res = sh.run(["git", "pull", "--ff-only", "--quiet"], cwd=repo, check=False)
    return ("ok", "updated") if res.returncode == 0 else ("skipped", "not on main or no upstream; nothing done")


def cmd_update(ctx: Ctx, args: argparse.Namespace) -> int:
    state = load_state(ctx)
    manifest = Path(args.manifest or state.get("manifest", ""))
    if not manifest.is_file():
        raise OnboardError("manifest not found: run `onboard.py init` first (or pass --manifest)")
    man = layers.load_manifest(str(manifest))
    # Ownership validation must happen before pulls, pin updates, restores, or other writes.
    ctx.sh.run([sys.executable, "-I", str(SUPEREGO / "tools" / "compose.py"), "--manifest", str(manifest),
                "--claude-home", str(ctx.claude), "--codex-home", str(ctx.codex), "--skills-only", "--dry-run"])
    a = {"name": state.get("name", ""), "github": state.get("github", "")}
    pinned_changed = False
    if not args.no_pull:
        for layer in man["layers"]:
            if layers.is_readonly(layer) and (layer.get("active", True) or layer.get("company")):
                before = layer.get("ref")
                status, detail = pull_layer(ctx, layer, args.upgrade)
                step(ctx, status, f"pull {layer['level']}", detail)
                pinned_changed |= layer.get("ref") != before
    if pinned_changed:
        raw = read_json(manifest)
        for entry in raw["layers"]:
            for layer in man["layers"]:
                if entry["level"] == layer["level"] and entry.get("repo") == layer.get("repo"):
                    entry["ref"] = layer.get("ref", "")
        write_json(manifest, raw)
        repo = manifest.parent
        if commit_all(ctx.sh, repo, "chore: pin the new superego release"):
            ctx.sh.run(["git", "push", "--quiet", "origin", "HEAD"], cwd=repo, check=False)
        man = layers.load_manifest(str(manifest))
    written: list[str] = []
    for layer in layers.active_layers(man):
        if layers.is_readonly(layer):
            written += restore_layer(layer, ctx.claude)
    compose(ctx, manifest, state)
    compose_company_homes(ctx, manifest, manifest.parent.parent, state)
    hits = output_hits(ctx, written, a)
    if hits:
        for h in hits[:20]:
            step(ctx, "LEAKED", "output", str(h))
        raise OnboardError("terms of another owner in the composed context; see above")
    state["written"] = sorted(set(state["written"]) | set(written))
    save_state(ctx, state)
    step(ctx, "ok", "composition", "CLAUDE.md and AGENTS.md updated")
    if args.push:
        for level in ("id", "ego"):  # the person's own layers; the collective is never written from here
            mine = [l for l in layers.writable_layers(man) if l["level"] == level]
            if not mine:
                continue
            layers.export(man, str(ctx.claude), level)
            repo = Path(mine[0]["path"])
            if commit_all(ctx.sh, repo, "chore(context): update my layer"):
                res = ctx.sh.run(["git", "push", "--quiet", "origin", "HEAD"], cwd=repo, check=False)
                step(ctx, "ok" if res.returncode == 0 else "failed", f"backup of {level}", "pushed" if res.returncode == 0
                     else (res.stderr or "push failed").strip()[:200])
            else:
                step(ctx, "skipped", f"backup of {level}", "no changes")
    return 0


