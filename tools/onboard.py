def cmd_contribute(ctx: Ctx, args: argparse.Namespace) -> int:
    state = load_state(ctx)
    if args.action == "start":
        man = layers.load_manifest(str(state["manifest"]))
        layer = next((l for l in layers.active_layers(man) if l["level"] == args.layer or l.get("name") == args.layer
                      or Path(l["path"]).name == args.layer), None)
        if not layer or not layers.is_readonly(layer):
            raise OnboardError("shared layer not found (use collective, ego or the repository name)")
        slug = re.sub(r"[^a-z0-9]+", "-", args.slug.lower()).strip("-")
        branch = f"contrib/{state['github']}/{slug}"
        repo = Path(layers.repo_root(layer["path"]))  # the superego layer lives inside the apparatus checkout
        work = repo.parent / "contrib" / f"{repo.name}-{slug}"
        ctx.sh.run(["git", "worktree", "add", "-b", branch, str(work), "HEAD"], cwd=repo)
        ctx.say(f"Edit in {work} (drafts in proposed/). Then: onboard.py contribute submit {work} -m \"feat: ...\"")
        return 0
    work = Path(args.path)
    if not (work / ".git").exists():
        raise OnboardError(f"{work} is not a folder created by `contribute start`")
    if not re.match(r"^(feat|fix|docs|chore|refactor|test)(\([^)]+\))?!?: .+", args.message):
        raise OnboardError("the message must follow Conventional Commits, for example: feat: add term X")
    if not commit_all(ctx.sh, work, args.message):
        raise OnboardError("nothing to submit: there are no changes")
    branch = ctx.sh.out(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=work)
    slug = "/".join(slug_of(ctx.sh.out(["git", "remote", "get-url", "origin"], cwd=work)))
    if ctx.sh.run(["git", "push", "--quiet", "-u", "origin", branch], cwd=work, check=False).returncode == 0:
        head = branch
    else:
        ctx.say("No write permission; trying through a fork.")
        ctx.sh.run(["gh", "repo", "fork", slug, "--remote=false", "--clone=false"], check=False)
        fork = f"{state['github']}/{slug.split('/')[1]}"
        ctx.sh.run(["git", "push", "--quiet", f"https://github.com/{fork}.git", f"{branch}:{branch}"], cwd=work)
        head = f"{state['github']}:{branch}"
    ctx.sh.run(["gh", "pr", "create", "--repo", slug, "--head", head, "--title", args.message,
                "--body", "Proposal for the shared layer. Project content only; no personal or company data."],
               interactive=True)
    return 0


