# --------------------------------------------------------------------------- environment and processes

@dataclass
class Sh:
    """Every external command goes through here (so tests can fake it)."""
    env: dict = field(default_factory=lambda: dict(os.environ))

    def run(self, argv: Sequence[str], cwd: Path | None = None, check: bool = True, interactive: bool = False,
            input: str | None = None, capture_stdout: bool = False) -> "subprocess.CompletedProcess[str]":
        """`input` goes to stdin (secrets never go on a command line); `capture_stdout` keeps a prompt interactive."""
        kw: dict = {} if interactive else {"capture_output": True}
        if interactive and capture_stdout:
            kw["stdout"] = subprocess.PIPE
        try:
            res = subprocess.run(list(argv), cwd=cwd, env=self.env, text=True, input=input, **kw)
        except OSError as exc:
            raise OnboardError(f"cannot run {argv[0]}: {exc}") from exc
        if check and res.returncode:
            raise OnboardError(f"{' '.join(map(str, argv[:4]))} failed: {(res.stderr or res.stdout or '').strip()[:300]}")
        return res

    def out(self, argv: Sequence[str], cwd: Path | None = None) -> str:
        return (self.run(argv, cwd=cwd).stdout or "").strip()


@dataclass
class Ctx:
    sh: Sh
    home: Path
    plat: str = field(default_factory=lambda: sys.platform)
    which: Callable[[str], str | None] = shutil.which
    say: Callable[[str], None] = print
    interactive: bool = field(default_factory=lambda: sys.stdin.isatty())

    @property
    def claude(self) -> Path:
        return ospaths.claude_home(self.sh.env, self.home)

    @property
    def codex(self) -> Path:
        return ospaths.codex_home(self.sh.env, self.home)

    @property
    def state_file(self) -> Path:
        return ospaths.state_dir(self.plat, self.sh.env, self.home) / "onboard-state.json"

    def ask(self, label: str, default: str = "") -> str:
        if not self.interactive:
            return default
        got = input(f"{label}" + (f" [{default}]" if default else "") + ": ").strip()
        return got or default


def step(ctx: Ctx, status: str, name: str, detail: str = "") -> None:
    ctx.say(f"[{status:>6}] {name}" + (f": {detail}" if detail else ""))


