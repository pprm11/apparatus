@dataclass(frozen=True)
class LayerSpec:
    level: str
    name: str
    url: str

    @property
    def repo(self) -> str:
        return repo_name(self.url)


def parse_layer(text: str) -> LayerSpec:
    m = re.fullmatch(r"(collective|ego):([a-z0-9][a-z0-9-]*)=(\S+)", text.strip())
    if not m:
        raise OnboardError(f"--layer must look like ego:NAME=URL or collective:NAME=URL, got {text!r}")
    return LayerSpec(m.group(1), m.group(2), m.group(3))


_URL = re.compile(r"(?:git@github\.com:|https://github\.com/|ssh://git@github\.com/)([^/\s]+)/([^/\s]+?)(?:\.git)?/?$")


def slug_of(url: str) -> tuple[str, str]:
    """(owner, repo) of a GitHub URL, or of a local path (owner = parent folder name)."""
    m = _URL.match(url.strip())
    if m:
        return m.group(1), m.group(2)
    if re.fullmatch(r"[\w.-]+/[\w.-]+", url.strip()):
        owner, repo = url.strip().split("/")
        return owner, re.sub(r"\.git$", "", repo)
    p = Path(url.strip().removeprefix("file://"))
    return p.parent.name, re.sub(r"\.git$", "", p.name)


def repo_name(url: str) -> str:
    return slug_of(url)[1]


def is_github(url: str) -> bool:
    return bool(_URL.match(url.strip()))


class GitHubHost:
    def __init__(self, sh: Sh):
        self.sh = sh

    def url(self, owner: str, repo: str) -> str:
        return f"https://github.com/{owner}/{repo}.git"

    def exists(self, owner: str, repo: str) -> bool:
        return self.sh.run(["gh", "repo", "view", f"{owner}/{repo}"], check=False).returncode == 0

    def publish(self, owner: str, repo: str, local: Path) -> None:
        self.sh.run(["gh", "repo", "create", f"{owner}/{repo}", "--private", "--source", str(local),
                     "--remote", "origin", "--push"])
        self.use_gh_credentials(local, self.url(owner, repo))

    def use_gh_credentials(self, repo_dir: Path, url: str) -> None:
        """HTTPS remote that authenticates through gh, whatever protocol the person's gh prefers (jobs have no tty)."""
        self.sh.run(["git", "remote", "set-url", "origin", url], cwd=repo_dir, check=False)
        self.sh.run(["git", "config", "credential.helper", "!gh auth git-credential"], cwd=repo_dir, check=False)

    def clone(self, url: str, dest: Path) -> None:
        dest.parent.mkdir(parents=True, exist_ok=True)
        if not is_github(url):
            self.sh.run(["git", "clone", "--quiet", url, str(dest)])
            return
        owner, repo = slug_of(url)
        https = f"https://github.com/{owner}/{repo}.git"
        res = self.sh.run(["git", "-c", "credential.helper=", "-c", "credential.helper=!gh auth git-credential",
                           "clone", "--quiet", https, str(dest)], check=False)
        if res.returncode:
            shutil.rmtree(dest, ignore_errors=True)
            raise OnboardError(f"no access to {owner}/{repo}. Ask the repository owner for a (read) invitation, accept it "
                               f"by e-mail and run init again. Detail: {(res.stderr or '').strip()[:200]}")
        self.use_gh_credentials(dest, https)


class LocalHost(GitHubHost):
    """Bare repos under a folder instead of GitHub: `owner/repo.git` below `base`."""

    def __init__(self, sh: Sh, base: Path):
        super().__init__(sh)
        self.base = base

    def url(self, owner: str, repo: str) -> str:
        return str(self.base / owner / f"{repo}.git")

    def exists(self, owner: str, repo: str) -> bool:
        return (self.base / owner / f"{repo}.git").is_dir()

    def publish(self, owner: str, repo: str, local: Path) -> None:
        bare = self.base / owner / f"{repo}.git"
        bare.parent.mkdir(parents=True, exist_ok=True)
        self.sh.run(["git", "init", "--bare", "--quiet", "-b", "main", str(bare)])
        self.sh.run(["git", "remote", "add", "origin", str(bare)], cwd=local)
        self.sh.run(["git", "push", "--quiet", "-u", "origin", "HEAD"], cwd=local)


def make_host(spec: str, sh: Sh) -> GitHubHost:
    if spec == "github":
        return GitHubHost(sh)
    if spec.startswith("local:"):
        return LocalHost(sh, Path(spec[6:]))
    raise OnboardError("--git-host must be github or local:DIR")


# --------------------------------------------------------------------------- small helpers

def under_home(path: Path, home: Path) -> str:
    try:
        return "~/" + path.resolve().relative_to(home.resolve()).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def fill(text: str, values: dict[str, str]) -> str:
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", v)
    return text


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def git_identity(sh: Sh, repo: Path, name: str, github: str) -> None:
    """Commits need an identity; use the person's own when git has one, else their GitHub no-reply address."""
    if not sh.run(["git", "config", "user.email"], cwd=repo, check=False).stdout.strip():
        sh.run(["git", "config", "user.email", f"{github}@users.noreply.github.com"], cwd=repo)
        sh.run(["git", "config", "user.name", name], cwd=repo)


def commit_all(sh: Sh, repo: Path, message: str) -> bool:
    sh.run(["git", "add", "-A"], cwd=repo)
    if not sh.out(["git", "status", "--porcelain"], cwd=repo):
        return False
    sh.run(["git", "commit", "--quiet", "-m", message], cwd=repo)
    return True


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data: dict) -> None:
    write(path, json.dumps(data, indent=1, ensure_ascii=False) + "\n")


