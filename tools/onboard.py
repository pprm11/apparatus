"""Install the layered agent context for ONE person who is not the owner of apparatus (Claude Code and Codex).

  python -I tools/onboard.py init --layer collective:NAME=URL --layer ego:NAME=URL [--name N] [--github USER]
  python -I tools/onboard.py update [--upgrade] [--push] [--no-pull]
  python -I tools/onboard.py doctor
  python -I tools/onboard.py contribute start LAYER SLUG | submit PATH -m "feat: ..."
  python -I tools/onboard.py uninstall [--purge-clones]

`init` creates the person's own private repos (self from templates/self, id from templates/id and, for each
collective, their own ego `ego-NAME` from templates/ego: the person's application of that collective) under
their GitHub account, attaches the collectives by URL (the only shared content layer, read-only clones), restores everything into
~/.claude, composes ~/.claude/CLAUDE.md and ~/.codex/AGENTS.md, registers the scheduled `update` job for this
OS and runs the doctor. It is pure Python (no bash), idempotent, and never reads or writes outside the
person's home. Nothing from the owner's personal or company layers is ever attached: shared layers are
scanned with generic and optional per-person privacy terms before they are restored, and the composed files after.
`--git-host local:DIR` replaces GitHub with bare repos under DIR (tests and offline demos).
"""
