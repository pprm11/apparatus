def prereqs(ctx: Ctx, need_gh: bool) -> list[tuple[str, bool, str]]:
    """(tool, ok, hint) for git, python and gh (when GitHub is used); claude and codex are advice only."""
    windows = ospaths.system(ctx.plat) == ospaths.WINDOWS
    mac = ospaths.system(ctx.plat) == ospaths.MACOS
    hint = {
        "git": "winget install --id Git.Git -e" if windows else "brew install git" if mac else "sudo apt-get install -y git",
        "gh": "winget install --id GitHub.cli -e" if windows else "brew install gh" if mac else
              "see https://github.com/cli/cli/blob/trunk/docs/install_linux.md",
    }
    out = [("git", bool(ctx.which("git")), hint["git"]), ("python", sys.version_info >= (3, 10), "install Python 3.10+")]
    if need_gh:
        out.append(("gh", bool(ctx.which("gh")), hint["gh"]))
    return out


def ensure_gh_login(ctx: Ctx) -> None:
    if ctx.sh.run(["gh", "auth", "status"], check=False).returncode == 0:
        return
    if not ctx.interactive:
        raise OnboardError("gh is not logged in: run `gh auth login` and try again")
    ctx.say("The GitHub CLI is not logged in. Opening the login (choose GitHub.com, HTTPS, browser).")
    ctx.sh.run(["gh", "auth", "login"], interactive=True)
    ctx.sh.run(["gh", "auth", "setup-git"], check=False)


