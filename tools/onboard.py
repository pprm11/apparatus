def own_repo_is_safe(ctx: Ctx, path: Path) -> bool:
    """A local clone of the person's own repo may be deleted only when nothing exists in it alone."""
    if not (path / ".git").exists():
        return True
    if ctx.sh.out(["git", "status", "--porcelain"], cwd=path):
        return False
    ahead = ctx.sh.run(["git", "rev-list", "--count", "@{u}..HEAD"], cwd=path, check=False)
    return ahead.returncode == 0 and ahead.stdout.strip() == "0"


def rmtree_force(path: Path) -> None:
    def onerr(func, p, _exc):
        os.chmod(p, 0o700)
        func(p)
    shutil.rmtree(path, onerror=onerr)


def is_link(p: Path) -> bool:
    return p.is_symlink() or (hasattr(p, "is_junction") and p.is_junction())


def cmd_uninstall(ctx: Ctx, args: argparse.Namespace) -> int:
    """Remove what the installer put on this machine. Remote repos and vault items stay unless asked, twice."""
    state = load_state(ctx)
    dry = args.dry_run
    verb = "would remove" if dry else "removed"
    removed: list[str] = []

    gone: set[str] = set()

    def covered(x: Path) -> bool:
        t = str(x)
        return any(t == g or t.startswith(g + os.sep) for g in gone)

    def would_be_empty(p: Path) -> bool:
        return all(covered(x) or (x.is_dir() and str(x) in created and would_be_empty(x)) for x in p.iterdir())

    def act(desc: str, fn: Callable[[], None] | None = None, path: Path | None = None) -> None:
        removed.append(desc)
        if path is not None:
            gone.add(str(path))
        if not dry and fn:
            fn()
        step(ctx, "dry" if dry else "ok", verb, desc)

    created = set(state.get("created_dirs", []))

    manifest = Path(state.get("manifest", ""))
    if args.delete_remote_repos:  # refuse before anything is removed
        confirm_remote_delete(ctx, args, state, dry)
    if state.get("jobs") and manifest.is_file():
        names = ", ".join(state["jobs"])
        act(f"scheduled jobs: {names}", lambda: scheduler.backend_for().remove(scheduler.jobs_for(manifest, ctx.plat, all_jobs=True)))
    skills = ctx.codex / "skills"
    if skills.is_dir():
        for link in sorted(skills.iterdir()):
            if is_link(link) and str(ctx.claude / "skills") in os.path.realpath(link).replace("/", os.sep):
                act(f"Codex skill link: {link}", lambda link=link: (os.rmdir(link) if os.name == "nt" and not link.is_symlink() else link.unlink()), link)
    for rel in state["written"]:
        f = ctx.claude / rel
        if f.is_file():
            act(f"copied file: {f}", f.unlink, f)
    agents = ctx.codex / "AGENTS.md"
    if agents.is_file() and GENERATED_CODEX in agents.read_text(encoding="utf-8", errors="replace")[:400]:
        act(f"generated AGENTS.md: {agents}", agents.unlink, agents)
    for key, bak in state.get("backups", {}).items():
        if Path(bak).is_file():
            target = (ctx.claude if key == "CLAUDE.md" else ctx.codex) / key
            act(f"backup restored: {target}", lambda bak=bak, target=target: shutil.move(bak, target), Path(bak))
    for extra in state.get("extra_files", []):
        if Path(extra).is_file():
            act(f"vault file (public key only): {extra}", Path(extra).unlink, Path(extra))
    age_key = ospaths.age_dir(ctx.home) / "id.txt"
    if args.remove_age_key and age_key.exists():
        if args.yes or (ctx.interactive and ctx.ask(f"Delete the local age key {age_key}? It only exists in the vault if you stored it there (y/n)", "n").lower().startswith("y")):
            act(f"local age key: {age_key}", lambda: __import__("keyfile").wipe(age_key), age_key)
        else:
            step(ctx, "kept", "local age key", str(age_key))
    for d in state.get("company_homes", []):
        if Path(d).is_dir():
            act(f"per-company homes: {d}", lambda d=d: rmtree_force(Path(d)), Path(d))
    if not args.keep_clones:
        own = {n for n in state.get("own_repos", [])}
        for c in state.get("clones", []):
            p = Path(c)
            if not p.exists():
                continue
            if p.name in own and not own_repo_is_safe(ctx, p):
                step(ctx, "kept", "clone with local-only work", f"{p} (has uncommitted changes or unpushed commits)")
                continue
            act(f"local clone: {p}", lambda p=p: rmtree_force(p), p)
        contrib = Path(state.get("clones", [""])[0]).parent / "contrib" if state.get("clones") else None
        if contrib and contrib.is_dir():
            act(f"local proposals (contribute): {contrib}", lambda: rmtree_force(contrib), contrib)
    st = ospaths.state_dir(ctx.plat, ctx.sh.env, ctx.home)
    if st.exists() and state.get("manifest"):
        act(f"state, logs and locks: {st}", lambda: shutil.rmtree(st, ignore_errors=True), st)
    created |= {str(ctx.codex / "skills")}
    for rel in state["written"]:
        for anc in (ctx.claude / rel).parents:
            if anc == ctx.claude:
                break
            created.add(str(anc))
    created -= {str(ctx.claude)} - set(state.get("created_dirs", []))
    for d in sorted(created, key=lambda x: len(Path(x).parts), reverse=True):
        p = Path(d)
        if p.is_dir() and would_be_empty(p):
            act(f"folder the installer created: {p}", p.rmdir, p)
    if args.delete_remote_repos:
        delete_remote(ctx, state, dry)
    if not removed:
        step(ctx, "ok", "uninstall", "nothing to remove (already clean)")
    else:
        step(ctx, "ok", "uninstall", f"{len(removed)} item(s) {'would be removed' if dry else 'removed'}"
             + ("" if args.delete_remote_repos else "; GitHub and Bitwarden were not touched"))
    step(ctx, "note", "git", "the credential helper set by `gh auth setup-git` (global git config) was kept: it belongs to gh, not to this installer")
    return 0


def confirm_remote_delete(ctx: Ctx, args: argparse.Namespace, state: dict, dry: bool) -> None:
    owner = state.get("github", "")
    repos = [f"{owner}/{r}" for r in state.get("own_repos", [])]
    if not owner or args.confirm_remote_delete != owner:
        raise OnboardError(f"to delete remote repositories also pass --confirm-remote-delete {owner or 'YOUR_USER'}")
    if not dry:
        if ctx.interactive:
            if ctx.ask(f"Type DELETE to delete on GitHub: {', '.join(repos)}", "") != "DELETE":
                raise OnboardError("cancelled: nothing was deleted")
        elif not args.i_am_sure:
            raise OnboardError("no terminal: also confirm with --i-am-sure")


def delete_remote(ctx: Ctx, state: dict, dry: bool) -> None:
    """Only the person's own repos, never the vault. Confirmations were checked before anything ran."""
    for r in state.get("own_repos", []):
        full = f"{state.get('github', '')}/{r}"
        step(ctx, "dry" if dry else "ok", "would delete on GitHub" if dry else "deleted on GitHub", full)
        if not dry:
            ctx.sh.run(["gh", "repo", "delete", full, "--yes"], check=False)


# --------------------------------------------------------------------------- restore (existing person, new machine)

def cmd_restore(ctx: Ctx, args: argparse.Namespace) -> int:
    """Existing person on a new machine: clone their self, every layer it lists, unlock their vault, decrypt the
    sealed paths and the secrets backup without overwriting existing files, restore, compose, jobs, doctor."""
    host = make_host(args.git_host, ctx.sh)
    github = args.github or ctx.ask("Your GitHub username", "")
    if not github:
        raise OnboardError("--github is missing (the account that holds your self)")
    missing = [(t, h) for t, ok, h in prereqs(ctx, args.git_host == "github") if not ok]
    if missing:
        for t, h in missing:
            step(ctx, "missing", t, h)
        raise OnboardError("install what is missing and run again")
    if args.git_host == "github":
        ensure_gh_login(ctx)
        ctx.sh.run(["gh", "auth", "setup-git"], check=False)
    state = load_state(ctx)
    codes = layers_folder(ctx, args.codes)
    self_repo_dir = codes / args.self_repo
    if not (self_repo_dir / ".git").exists():
        host.clone(host.url(github, args.self_repo), self_repo_dir)
        state["clones"].append(str(self_repo_dir))
    step(ctx, "ok", "self", str(self_repo_dir))
    manifest = self_repo_dir / "manifest.json"
    raw = read_json(manifest)
    for entry in raw["layers"]:
        if not entry.get("active", True) or not entry.get("repo"):
            continue
        dest = Path(os.path.expanduser(entry["path"]))
        if not (dest / ".git").exists():
            if dest in (SUPEREGO, SUPEREGO / "superego"):
                continue
            host.clone(entry["repo"], dest)
            state["clones"].append(str(dest))
            step(ctx, "ok", f"layer {entry['level']}", str(dest))
    state.update(manifest=str(manifest), github=github)
    man = layers.load_manifest(str(manifest))
    ctx.claude.mkdir(parents=True, exist_ok=True)
    identity_ok = False
    if args.vault != "skip":
        missing_tools = ensure_tools(ctx, ("bw", "age"))
        vault = onboard_vault.Vault(ctx.sh, ctx.say)
        if not missing_tools:
            vault.set_region(args.bw_region)
        if not missing_tools and vault.unlock(ctx.interactive):
            note = vault.read_note()
            if onboard_vault.has_key(note):
                import keyfile  # noqa: PLC0415
                with keyfile.temp_secret(note, ospaths.state_dir(ctx.plat, ctx.sh.env, ctx.home) / "tmp", "age-id", ctx.plat) as ident:
                    for layer in layers.active_layers(man):
                        un = Path(layer["path"]) / "tools" / "unseal.py"
                        if un.is_file():
                            res = ctx.sh.run([sys.executable, "-I", str(un), "--into", str(ctx.claude), "--identity", str(ident)],
                                             check=False)
                            step(ctx, "ok" if res.returncode == 0 else "failed", f"sealed of {layer['level']}",
                                 "decrypted without overwriting what already exists" if res.returncode == 0
                                 else (res.stderr or res.stdout or "").strip()[-200:])
                        if (Path(layer["path"]) / "sealed" / "secrets" / "manifest.json.age").is_file():
                            res = ctx.sh.run([sys.executable, "-I", str(SUPEREGO / "tools" / "secrets_backup.py"), "restore",
                                              "--identity", str(ident)], check=False)
                            step(ctx, "ok" if res.returncode == 0 else "failed", "secrets",
                                 "restored without overwriting existing files" if res.returncode == 0
                                 else (res.stderr or res.stdout or "").strip()[-200:])
                identity_ok = True
            else:
                step(ctx, "warn", "vault", f"the note {onboard_vault.NOTE} does not exist in your vault: sealed/ and secrets are left for later")
        else:
            step(ctx, "skipped", "vault", "locked or no bw: run `onboard.py restore` again with the vault open")
    written: list[str] = []
    for layer in layers.active_layers(man):
        written += restore_layer(layer, ctx.claude)
    compose(ctx, manifest, state)
    state["written"] = sorted(set(state["written"]) | set(written) | {"CLAUDE.md"})
    step(ctx, "ok", "composition", f"{ctx.claude / 'CLAUDE.md'} and {ctx.codex / 'AGENTS.md'}")
    jobs = scheduler.jobs_for(manifest, ctx.plat)
    if args.jobs == "apply":
        try:
            be = scheduler.backend_for()
            state["jobs"] = be.install(jobs)
            step(ctx, "ok", "scheduled jobs", f"{be.name}: {', '.join(state['jobs'])}")
        except Exception as exc:
            step(ctx, "failed", "scheduled jobs", f"{type(exc).__name__}: {str(exc)[:150]}")
    else:
        step(ctx, "skipped", "scheduled jobs", f"--jobs {args.jobs}")
    save_state(ctx, state)
    if raw.get("runner") == "python":
        run_initial_sync(ctx, manifest)
    step(ctx, "ok" if identity_ok or args.vault == "skip" else "warn", "restore", "done")
    if raw.get("runner") == "python":
        return report_doctor(ctx, manifest, args.git_host == "github")
    e = doctor.Env(plat=ctx.plat, env=ctx.sh.env, home=ctx.home)
    checks = doctor.collect(e, manifest)
    ctx.say(doctor.render(checks, ctx.plat))
    return 1 if any(c.status == doctor.FAIL for c in checks) else 0


